func Generate(catalog *Catalog) ([]Output, error) {
	goData, err := generateGo(catalog)
	if err != nil {
		return nil, err
	}

	return []Output{
		{Path: "subjects/subjects.gen.go", Content: goData},
		{Path: "csharp/Subjects.g.cs", Content: generateCSharp(catalog)},
		{Path: "lib/subjects.ts", Content: generateTypeScript(catalog)},
		{Path: "src/cobotar_protocol/subjects.py", Content: generatePython(catalog)},
		{Path: "documentation/subjects.md", Content: generateMarkdown(catalog)},
	}, nil
}

func generateGo(catalog *Catalog) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by subjectgen. DO NOT EDIT.\n\npackage subjects\n\n")
	out.WriteString("import (\n\t\"fmt\"\n\t\"strings\"\n)\n\n")
	out.WriteString("type Definition struct {\n\tID string\n\tPattern string\n\tLifecycle string\n\tConformance string\n\tInteraction string\n\tPayload string\n\tRequest string\n\tEmptyRequest bool\n\tSuccessReply string\n\tFailureReply string\n\tPublishers []string\n\tConsumers []string\n\tTrackingIssue string\n}\n\n")
	out.WriteString("var Catalog = []Definition{\n")
	for _, route := range catalog.Routes {
		fmt.Fprintf(&out, "\t{ID: %s, Pattern: %s, Lifecycle: %s, Conformance: %s, Interaction: %s, Payload: %s, Request: %s, EmptyRequest: %t, SuccessReply: %s, FailureReply: %s, Publishers: %#v, Consumers: %#v, TrackingIssue: %s},\n",
			strconv.Quote(route.ID), strconv.Quote(route.Pattern), strconv.Quote(route.Lifecycle), strconv.Quote(route.Conformance.Mode), strconv.Quote(route.Interaction), strconv.Quote(route.Payload), strconv.Quote(route.Request), route.EmptyRequest, strconv.Quote(route.Replies.Success), strconv.Quote(route.Replies.Failure), route.Publishers, route.Consumers, strconv.Quote(route.Conformance.TrackingIssue))
	}
	out.WriteString("}\n\n")
	out.WriteString("func buildSubject(pattern string, values map[string]string) (string, error) {\n\tresult := pattern\n\tfor name, value := range values {\n\t\tif err := validateSubjectToken(name, value); err != nil { return \"\", err }\n\t\tresult = strings.ReplaceAll(result, \"{\"+name+\"}\", value)\n\t}\n\treturn result, nil\n}\n\n")
	out.WriteString("func validateSubjectToken(name, value string) error {\n\tif value == \"\" { return fmt.Errorf(\"subject parameter %s is empty\", name) }\n\tif strings.ContainsAny(value, \".*> \\t\\r\\n\") { return fmt.Errorf(\"subject parameter %s contains a separator, wildcard, or whitespace\", name) }\n\treturn nil\n}\n\n")

	for _, route := range catalog.Routes {
		if route.Lifecycle == "retired" {
			continue
		}
		name := pascalName(route.ID)
		writeGoComment(&out, name, route)
		parameters := route.ParameterList()
		if len(parameters) == 0 {
			fmt.Fprintf(&out, "const %s = %s\n\n", name, strconv.Quote(route.Pattern))
			continue
		}
		fmt.Fprintf(&out, "func %s(%s) (string, error) {\n\treturn buildSubject(%s, map[string]string{%s})\n}\n\n",
			name, goParameters(parameters), strconv.Quote(route.Pattern), goParameterMap(parameters))
		fmt.Fprintf(&out, "func Must%s(%s) string {\n\tsubject, err := %s(%s)\n\tif err != nil { panic(err) }\n\treturn subject\n}\n\n",
			name, goParameters(parameters), name, goArguments(parameters))
		fmt.Fprintf(&out, "func Subscribe%sAny() string { return %s }\n\n", name, strconv.Quote(wildcardPattern(route)))
		for _, subscription := range route.Subscriptions {
			subscriptionName := "Subscribe" + name + pascalName(subscription.Name)
			subscriptionParameters := orderedSubscriptionParameters(route, subscription)
			fmt.Fprintf(&out, "func %s(%s) (string, error) {\n\treturn buildSubject(%s, map[string]string{%s})\n}\n\n",
				subscriptionName, goParameters(subscriptionParameters), strconv.Quote(partialWildcardPattern(route, subscription)), goParameterMap(subscriptionParameters))
		}
	}

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go helpers: %w", err)
	}
	return formatted, nil
}

func writeGoComment(out *bytes.Buffer, name string, route Route) {
	fmt.Fprintf(out, "// %s builds %s.\n", name, route.Pattern)
	if route.Lifecycle == "planned" || route.Conformance.Mode == "staged" {
		fmt.Fprintf(out, "// Experimental: lifecycle=%s, conformance=%s; see %s.\n", route.Lifecycle, route.Conformance.Mode, route.Conformance.TrackingIssue)
	}
}

func goParameters(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = camelName(parameter) + " string"
	}
	return strings.Join(parts, ", ")
}

func goParameterMap(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = strconv.Quote(parameter) + ": " + camelName(parameter)
	}
	return strings.Join(parts, ", ")
}

func goArguments(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = camelName(parameter)
	}
	return strings.Join(parts, ", ")
}

func generateTypeScript(catalog *Catalog) []byte {
	var out bytes.Buffer
	out.WriteString("// Code generated by subjectgen. DO NOT EDIT.\n\n")
	out.WriteString("export interface SubjectDefinition {\n  readonly id: string\n  readonly pattern: string\n  readonly lifecycle: string\n  readonly conformance: string\n  readonly interaction: string\n  readonly payload: string\n  readonly request: string\n  readonly emptyRequest: boolean\n  readonly successReply: string\n  readonly failureReply: string\n  readonly publishers: readonly string[]\n  readonly consumers: readonly string[]\n  readonly trackingIssue: string\n}\n\n")
	out.WriteString("export const subjectCatalog: readonly SubjectDefinition[] = [\n")
	for _, route := range catalog.Routes {
		fmt.Fprintf(&out, "  { id: %s, pattern: %s, lifecycle: %s, conformance: %s, interaction: %s, payload: %s, request: %s, emptyRequest: %t, successReply: %s, failureReply: %s, publishers: %s, consumers: %s, trackingIssue: %s },\n",
			jsString(route.ID), jsString(route.Pattern), jsString(route.Lifecycle), jsString(route.Conformance.Mode), jsString(route.Interaction), jsString(route.Payload), jsString(route.Request), route.EmptyRequest, jsString(route.Replies.Success), jsString(route.Replies.Failure), jsArray(route.Publishers), jsArray(route.Consumers), jsString(route.Conformance.TrackingIssue))
	}
	out.WriteString("]\n\n")
	out.WriteString("function buildSubject(pattern: string, values: Readonly<Record<string, string>>): string {\n  let result = pattern\n  for (const [name, value] of Object.entries(values)) {\n    validateSubjectToken(name, value)\n    result = result.split(`{${name}}`).join(value)\n  }\n  return result\n}\n\n")
	out.WriteString("function validateSubjectToken(name: string, value: string): void {\n  if (value.length === 0 || /[.*>\\s]/u.test(value)) {\n    throw new TypeError(`subject parameter ${name} is empty or contains a separator, wildcard, or whitespace`)\n  }\n}\n\n")
	for _, route := range catalog.Routes {
		if route.Lifecycle == "retired" {
			continue
		}
		name := camelName(route.ID)
		fmt.Fprintf(&out, "/** Builds `%s`.\n", route.Pattern)
		if route.Lifecycle == "planned" || route.Conformance.Mode == "staged" {
			fmt.Fprintf(&out, " * @experimental lifecycle=%s, conformance=%s; see %s.\n", route.Lifecycle, route.Conformance.Mode, route.Conformance.TrackingIssue)
		}
		out.WriteString(" */\n")
		parameters := route.ParameterList()
		if len(parameters) == 0 {
			fmt.Fprintf(&out, "export const %s = %s\n\n", name, jsString(route.Pattern))
			continue
		}
		fmt.Fprintf(&out, "export function %s(%s): string {\n  return buildSubject(%s, { %s })\n}\n\n",
			name, typescriptParameters(parameters), jsString(route.Pattern), typescriptParameterMap(parameters))
		fmt.Fprintf(&out, "export function subscribe%sAny(): string { return %s }\n\n", pascalName(route.ID), jsString(wildcardPattern(route)))
		for _, subscription := range route.Subscriptions {
			subscriptionParameters := orderedSubscriptionParameters(route, subscription)
			fmt.Fprintf(&out, "export function subscribe%s%s(%s): string {\n  return buildSubject(%s, { %s })\n}\n\n",
				pascalName(route.ID), pascalName(subscription.Name), typescriptParameters(subscriptionParameters), jsString(partialWildcardPattern(route, subscription)), typescriptParameterMap(subscriptionParameters))
		}
	}
	return out.Bytes()
}

func generatePython(catalog *Catalog) []byte {
	var out bytes.Buffer
	out.WriteString("# Code generated by subjectgen. DO NOT EDIT.\n\nfrom typing import Dict, Tuple\n\n")
	out.WriteString("SUBJECT_CATALOG: Tuple[Dict[str, object], ...] = (\n")
	for _, route := range catalog.Routes {
		fmt.Fprintf(&out, "    {\"id\": %s, \"pattern\": %s, \"lifecycle\": %s, \"conformance\": %s, \"interaction\": %s, \"payload\": %s, \"request\": %s, \"empty_request\": %s, \"success_reply\": %s, \"failure_reply\": %s, \"publishers\": %s, \"consumers\": %s, \"tracking_issue\": %s},\n",
			pyString(route.ID), pyString(route.Pattern), pyString(route.Lifecycle), pyString(route.Conformance.Mode), pyString(route.Interaction), pyString(route.Payload), pyString(route.Request), pyBool(route.EmptyRequest), pyString(route.Replies.Success), pyString(route.Replies.Failure), pyTuple(route.Publishers), pyTuple(route.Consumers), pyString(route.Conformance.TrackingIssue))
	}
	out.WriteString(")\n\n")
	out.WriteString("def _build_subject(pattern: str, **values: str) -> str:\n    result = pattern\n    for name, value in values.items():\n        _validate_subject_token(name, value)\n        result = result.replace(\"{\" + name + \"}\", value)\n    return result\n\n")
	out.WriteString("def _validate_subject_token(name: str, value: str) -> None:\n    if not value or any(character in value for character in \".*> \\t\\r\\n\"):\n        raise ValueError(f\"subject parameter {name} is empty or contains a separator, wildcard, or whitespace\")\n\n")
	for _, route := range catalog.Routes {
		if route.Lifecycle == "retired" {
			continue
		}
		name := snakeName(route.ID)
		parameters := route.ParameterList()
		if len(parameters) == 0 {
			fmt.Fprintf(&out, "%s = %s\n\n", strings.ToUpper(name), pyString(route.Pattern))
			continue
		}
		fmt.Fprintf(&out, "def %s(%s) -> str:\n    \"\"\"Build `%s`.", name, typedParameters(parameters, ": str"), route.Pattern)
		if route.Lifecycle == "planned" || route.Conformance.Mode == "staged" {
			fmt.Fprintf(&out, " Experimental: %s/%s; see %s.", route.Lifecycle, route.Conformance.Mode, route.Conformance.TrackingIssue)
		}
		fmt.Fprintf(&out, "\"\"\"\n    return _build_subject(%s, %s)\n\n", pyString(route.Pattern), pythonKeywordParameters(parameters))
		fmt.Fprintf(&out, "def subscribe_%s_any() -> str:\n    \"\"\"Subscribe to every concrete `%s` subject.\"\"\"\n    return %s\n\n", name, route.ID, pyString(wildcardPattern(route)))
		for _, subscription := range route.Subscriptions {
			subscriptionParameters := orderedSubscriptionParameters(route, subscription)
			fmt.Fprintf(&out, "def subscribe_%s_%s(%s) -> str:\n    \"\"\"Build the `%s` partial-wildcard subscription.\"\"\"\n    return _build_subject(%s, %s)\n\n",
				name, snakeName(subscription.Name), typedParameters(subscriptionParameters, ": str"), subscription.Name, pyString(partialWildcardPattern(route, subscription)), pythonKeywordParameters(subscriptionParameters))
		}
	}
	return out.Bytes()
}

func generateCSharp(catalog *Catalog) []byte {
	var out bytes.Buffer
	out.WriteString("// Code generated by subjectgen. DO NOT EDIT.\nusing System;\nusing System.Collections.Generic;\n\nnamespace Messages {\n    public sealed class SubjectDefinition {\n        public string Id { get; set; }\n        public string Pattern { get; set; }\n        public string Lifecycle { get; set; }\n        public string Conformance { get; set; }\n        public string Interaction { get; set; }\n        public string Payload { get; set; }\n        public string Request { get; set; }\n        public bool EmptyRequest { get; set; }\n        public string SuccessReply { get; set; }\n        public string FailureReply { get; set; }\n        public IReadOnlyList<string> Publishers { get; set; }\n        public IReadOnlyList<string> Consumers { get; set; }\n        public string TrackingIssue { get; set; }\n    }\n\n    public static class Subjects {\n")
	out.WriteString("        public static readonly IReadOnlyList<SubjectDefinition> Catalog = new SubjectDefinition[] {\n")
	for _, route := range catalog.Routes {
		fmt.Fprintf(&out, "            new SubjectDefinition { Id = %s, Pattern = %s, Lifecycle = %s, Conformance = %s, Interaction = %s, Payload = %s, Request = %s, EmptyRequest = %s, SuccessReply = %s, FailureReply = %s, Publishers = %s, Consumers = %s, TrackingIssue = %s },\n",
			csString(route.ID), csString(route.Pattern), csString(route.Lifecycle), csString(route.Conformance.Mode), csString(route.Interaction), csString(route.Payload), csString(route.Request), csBool(route.EmptyRequest), csString(route.Replies.Success), csString(route.Replies.Failure), csArray(route.Publishers), csArray(route.Consumers), csString(route.Conformance.TrackingIssue))
	}
	out.WriteString("        };\n\n")
	for _, route := range catalog.Routes {
		if route.Lifecycle == "retired" {
			continue
		}
		name := pascalName(route.ID)
		fmt.Fprintf(&out, "        /// <summary>Builds %s.", route.Pattern)
		if route.Lifecycle == "planned" || route.Conformance.Mode == "staged" {
			fmt.Fprintf(&out, " Experimental: %s/%s; see %s.", route.Lifecycle, route.Conformance.Mode, route.Conformance.TrackingIssue)
		}
		out.WriteString("</summary>\n")
		parameters := route.ParameterList()
		if len(parameters) == 0 {
			fmt.Fprintf(&out, "        public const string %s = %s;\n\n", name, csString(route.Pattern))
			continue
		}
		fmt.Fprintf(&out, "        public static string %s(%s) => BuildSubject(%s, %s);\n", name, csharpParameters(parameters), csString(route.Pattern), csharpPairs(parameters))
		fmt.Fprintf(&out, "        public static string Subscribe%sAny() => %s;\n\n", name, csString(wildcardPattern(route)))
		for _, subscription := range route.Subscriptions {
			subscriptionParameters := orderedSubscriptionParameters(route, subscription)
			fmt.Fprintf(&out, "        public static string Subscribe%s%s(%s) => BuildSubject(%s, %s);\n\n",
				name, pascalName(subscription.Name), csharpParameters(subscriptionParameters), csString(partialWildcardPattern(route, subscription)), csharpPairs(subscriptionParameters))
		}
	}
	out.WriteString("        private static string BuildSubject(string pattern, params string[] namesAndValues) {\n            var result = pattern;\n            for (var index = 0; index < namesAndValues.Length; index += 2) {\n                var name = namesAndValues[index];\n                var value = namesAndValues[index + 1];\n                ValidateSubjectToken(name, value);\n                result = result.Replace(\"{\" + name + \"}\", value);\n            }\n            return result;\n        }\n\n        private static void ValidateSubjectToken(string name, string value) {\n            if (string.IsNullOrEmpty(value) || value.IndexOfAny(new[] { '.', '*', '>', ' ', '\\t', '\\r', '\\n' }) >= 0) {\n                throw new ArgumentException($\"Subject parameter {name} is empty or contains a separator, wildcard, or whitespace.\", name);\n            }\n        }\n    }\n}\n")
	return out.Bytes()
}

func generateMarkdown(catalog *Catalog) []byte {
	var out bytes.Buffer
	out.WriteString("# NATS subject catalog\n\nThis file is generated from `subjects/catalog.yaml`. Do not edit it directly.\n\n")
	fmt.Fprintf(&out, "Catalog conformance: **%s**", catalog.Conformance.Mode)
	if catalog.Conformance.TrackingIssue != "" {
		fmt.Fprintf(&out, " ([%s](https://github.com/%s))", catalog.Conformance.TrackingIssue, strings.Replace(catalog.Conformance.TrackingIssue, "#", "/issues/", 1))
	}
	out.WriteString(".\n\n")
	out.WriteString("- **planned** reserves a contract while its message types or implementations may still be incomplete.\n- **active** has complete catalog metadata and is the current contract; **deprecated** remains supported until retirement.\n- **retired** reserves the old ID and pattern but generates no helper.\n- **staged** permits incremental cross-repository rollout, does not assert that every component has migrated, and requires a tracking issue.\n- **enforced** declares that every listed component is expected to conform to the catalog entry.\n\n")
	out.WriteString("| ID | Pattern | Lifecycle | Conformance | Messages | Publishers | Consumers |\n|---|---|---|---|---|---|---|\n")
	for _, route := range catalog.Routes {
		messages := route.Payload
		if route.Interaction == "request_reply" {
			request := route.Request
			if route.EmptyRequest {
				request = "(empty)"
			} else if request == "" {
				request = "(TBD)"
			}
			success, failure := route.Replies.Success, route.Replies.Failure
			if success == "" {
				success = "(TBD)"
			}
			if failure == "" {
				failure = "(TBD)"
			}
			messages = fmt.Sprintf("%s → %s / %s", request, success, failure)
		}
		fmt.Fprintf(&out, "| `%s` | `%s` | %s | %s | %s | %s | %s |\n", route.ID, route.Pattern, route.Lifecycle, route.Conformance.Mode, markdownEscape(messages), strings.Join(route.Publishers, ", "), strings.Join(route.Consumers, ", "))
	}
	out.WriteString("\nFor request/reply routes, publishers are requesters and consumers are responders. These lists describe intended ownership; staged conformance does not claim that every implementation has landed.\n")
	out.WriteString("\n## Naming rules\n\n- Literal tokens use lower_snake_case.\n- Parameters occupy exactly one NATS token and reject `.`, `*`, `>`, whitespace, and empty values.\n- Concrete publishers and requesters never use wildcards. Generated `Subscribe…Any` and named partial-subscription helpers introduce wildcards explicitly.\n- Entity and routing identifiers follow the operation token unless a catalog entry documents a different order.\n- Planned and staged helpers are experimental; their presence does not guarantee runtime availability.\n")
	return out.Bytes()
}

func wildcardPattern(route Route) string {
	pattern := route.Pattern
	for _, parameter := range route.ParameterList() {
		pattern = strings.ReplaceAll(pattern, "{"+parameter+"}", "*")
	}
	return pattern
}

func partialWildcardPattern(route Route, subscription Subscription) string {
	concrete := make(map[string]struct{}, len(subscription.Parameters))
	for _, parameter := range subscription.Parameters {
		concrete[parameter] = struct{}{}
	}
	pattern := route.Pattern
	for _, parameter := range route.ParameterList() {
		if _, ok := concrete[parameter]; !ok {
			pattern = strings.ReplaceAll(pattern, "{"+parameter+"}", "*")
		}
	}
	return pattern
}

func orderedSubscriptionParameters(route Route, subscription Subscription) []string {
	selected := make(map[string]struct{}, len(subscription.Parameters))
	for _, parameter := range subscription.Parameters {
		selected[parameter] = struct{}{}
	}
	var parameters []string
	for _, parameter := range route.ParameterList() {
		if _, ok := selected[parameter]; ok {
			parameters = append(parameters, parameter)
		}
	}
	return parameters
}

func typedParameters(parameters []string, suffix string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = parameter + suffix
	}
	return strings.Join(parts, ", ")
}

func typescriptParameters(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = camelName(parameter) + ": string"
	}
	return strings.Join(parts, ", ")
}

func typescriptParameterMap(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = parameter + ": " + camelName(parameter)
	}
	return strings.Join(parts, ", ")
}

func pythonKeywordParameters(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = parameter + "=" + parameter
	}
	return strings.Join(parts, ", ")
}

func csharpParameters(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = "string " + camelName(parameter)
	}
	return strings.Join(parts, ", ")
}

func csharpPairs(parameters []string) string {
	parts := make([]string, 0, len(parameters)*2)
	for _, parameter := range parameters {
		parts = append(parts, csString(parameter), camelName(parameter))
	}
	return strings.Join(parts, ", ")
}

func jsString(value string) string { return strconv.Quote(value) }
func pyString(value string) string { return strconv.Quote(value) }
func csString(value string) string { return strconv.Quote(value) }
func pyBool(value bool) string {
	if value {
		return "True"
	}
	return "False"
}
func csBool(value bool) string {
	if value {
		return "true"
	}
	return "false"
}

func jsArray(values []string) string { return "[" + quotedJoin(values) + "]" }
func csArray(values []string) string { return "new[] { " + quotedJoin(values) + " }" }
func pyTuple(values []string) string {
	if len(values) == 1 {
		return "(" + pyString(values[0]) + ",)"
	}
	return "(" + quotedJoin(values) + ")"
}

func quotedJoin(values []string) string {
	quoted := make([]string, len(values))
	for i, value := range values {
		quoted[i] = strconv.Quote(value)
	}
	return strings.Join(quoted, ", ")
}

func markdownEscape(value string) string { return strings.ReplaceAll(value, "|", "\\|") }

func sortOutputs(outputs []Output) {
	sort.Slice(outputs, func(i, j int) bool { return outputs[i].Path < outputs[j].Path })
}
