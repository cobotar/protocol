func Generate(catalog *Catalog) ([]Output, error) {
	goData, err := generateGo(catalog)
	if err != nil {
		return nil, err
	}

	return []Output{
		{Path: "subjects/subjects.gen.go", Content: goData},
		{Path: "csharp/Subjects.g.cs", Content: generateCSharp(catalog)},
		{Path: "lib/subjects.ts", Content: generateTypeScript(catalog)},
		{Path: "src/cobotar_protocol/subjects.py", Content: generatePython(catalog)},
		{Path: "documentation/subjects.md", Content: generateMarkdown(catalog)},
	}, nil
}

func generateGo(catalog *Catalog) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by subjectgen. DO NOT EDIT.\n\npackage subjects\n\n")
	out.WriteString("import (\n\t\"fmt\"\n\t\"strings\"\n)\n\n")
	writeGoEntities(&out, catalog)
	out.WriteString("type Definition struct {\n\tID string\n\tPattern string\n\tFamily string\n\tEntity string\n\tLifecycle string\n\tConformance string\n\tInteraction string\n\tPayload string\n\tRequest string\n\tEmptyRequest bool\n\tSuccessReply string\n\tFailureReply string\n\tPublishers []string\n\tConsumers []string\n\tTrackingIssue string\n}\n\n")
	out.WriteString("var Catalog = []Definition{\n")
	for _, route := range catalog.AllRoutes() {
		fmt.Fprintf(&out, "\t{ID: %s, Pattern: %s, Family: %s, Entity: %s, Lifecycle: %s, Conformance: %s, Interaction: %s, Payload: %s, Request: %s, EmptyRequest: %t, SuccessReply: %s, FailureReply: %s, Publishers: %#v, Consumers: %#v, TrackingIssue: %s},\n",
			strconv.Quote(route.ID), strconv.Quote(route.Pattern), strconv.Quote(route.FamilyID()), strconv.Quote(route.EntityName()), strconv.Quote(route.Lifecycle), strconv.Quote(route.Conformance.Mode), strconv.Quote(route.Interaction), strconv.Quote(route.Payload), strconv.Quote(route.Request), route.EmptyRequest, strconv.Quote(route.Replies.Success), strconv.Quote(route.Replies.Failure), route.Publishers, route.Consumers, strconv.Quote(route.Conformance.TrackingIssue))
	}
	out.WriteString("}\n\n")
	out.WriteString("func buildSubject(pattern string, values map[string]string) (string, error) {\n\tresult := pattern\n\tfor name, value := range values {\n\t\tif err := validateSubjectToken(name, value); err != nil { return \"\", err }\n\t\tresult = strings.ReplaceAll(result, \"{\"+name+\"}\", value)\n\t}\n\treturn result, nil\n}\n\n")
	out.WriteString("func validateSubjectToken(name, value string) error {\n\tif value == \"\" { return fmt.Errorf(\"subject parameter %s is empty\", name) }\n\tif strings.ContainsAny(value, \".*> \\t\\r\\n\") { return fmt.Errorf(\"subject parameter %s contains a separator, wildcard, or whitespace\", name) }\n\treturn nil\n}\n\n")

	for _, route := range catalog.AllRoutes() {
		if route.Lifecycle == "retired" {
			continue
		}
		name := pascalName(route.ID)
		writeGoComment(&out, name, route)
		parameters := route.ParameterList()
		if len(parameters) == 0 {
			fmt.Fprintf(&out, "const %s = %s\n\n", name, strconv.Quote(route.Pattern))
			continue
		}
		fmt.Fprintf(&out, "func %s(%s) (string, error) {\n\treturn buildSubject(%s, map[string]string{%s})\n}\n\n",
			name, goParameters(parameters), strconv.Quote(route.Pattern), goParameterMap(parameters))
		fmt.Fprintf(&out, "func Must%s(%s) string {\n\tsubject, err := %s(%s)\n\tif err != nil { panic(err) }\n\treturn subject\n}\n\n",
			name, goParameters(parameters), name, goArguments(parameters))
		fmt.Fprintf(&out, "func Subscribe%sAny() string { return %s }\n\n", name, strconv.Quote(wildcardPattern(route)))
		for _, subscription := range route.Subscriptions {
			subscriptionName := "Subscribe" + name + pascalName(subscription.Name)
			subscriptionParameters := orderedSubscriptionParameters(route, subscription)
			fmt.Fprintf(&out, "func %s(%s) (string, error) {\n\treturn buildSubject(%s, map[string]string{%s})\n}\n\n",
				subscriptionName, goParameters(subscriptionParameters), strconv.Quote(partialWildcardPattern(route, subscription)), goParameterMap(subscriptionParameters))
		}
	}
	for _, family := range catalog.RouteFamilies {
		if family.Lifecycle == "retired" {
			continue
		}
		name := pascalName(family.ID)
		writeGoComment(&out, name, family.Route)
		parameters := family.ParameterList()
		fmt.Fprintf(&out, "func %s(%s) (string, error) {\n\tif err := validateEntitySet(%s, %s, entity); err != nil { return \"\", err }\n\treturn buildSubject(%s, map[string]string{%s})\n}\n\n",
			name, goFamilyParameters(parameters), strconv.Quote(family.ID), strconv.Quote(family.EntitySet), strconv.Quote(family.Pattern), goFamilyParameterMap(parameters))
		fmt.Fprintf(&out, "func Must%s(%s) string {\n\tsubject, err := %s(%s)\n\tif err != nil { panic(err) }\n\treturn subject\n}\n\n",
			name, goFamilyParameters(parameters), name, goArguments(parameters))
		fmt.Fprintf(&out, "func Subscribe%sAny() string { return %s }\n\n", name, strconv.Quote(wildcardPattern(family.Route)))
		for _, subscription := range family.Subscriptions {
			subscriptionName := "Subscribe" + name + pascalName(subscription.Name)
			subscriptionParameters := orderedSubscriptionParameters(family.Route, subscription)
			fmt.Fprintf(&out, "func %s(%s) (string, error) {\n\tif err := validateEntitySet(%s, %s, entity); err != nil { return \"\", err }\n\treturn buildSubject(%s, map[string]string{%s})\n}\n\n",
				subscriptionName, goFamilyParameters(subscriptionParameters), strconv.Quote(family.ID), strconv.Quote(family.EntitySet), strconv.Quote(partialWildcardPattern(family.Route, subscription)), goFamilyParameterMap(subscriptionParameters))
		}
	}

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go helpers: %w", err)
	}
	return formatted, nil
}

func writeGoComment(out *bytes.Buffer, name string, route Route) {
	fmt.Fprintf(out, "// %s builds %s.\n", name, route.Pattern)
	if route.Lifecycle == "planned" || route.Conformance.Mode == "staged" {
		fmt.Fprintf(out, "// Experimental: lifecycle=%s, conformance=%s; see %s.\n", route.Lifecycle, route.Conformance.Mode, route.Conformance.TrackingIssue)
	}
}

func goParameters(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = camelName(parameter) + " string"
	}
	return strings.Join(parts, ", ")
}

func goParameterMap(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = strconv.Quote(parameter) + ": " + camelName(parameter)
	}
	return strings.Join(parts, ", ")
}

func goArguments(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		parts[i] = camelName(parameter)
	}
	return strings.Join(parts, ", ")
}

func writeGoEntities(out *bytes.Buffer, catalog *Catalog) {
	out.WriteString("type EntityName string\n\nconst (\n")
	for _, entity := range catalog.Entities {
		fmt.Fprintf(out, "\tEntity%s EntityName = %s\n", pascalName(entity.Name), strconv.Quote(entity.Name))
	}
	out.WriteString(")\n\nvar EntitySets = map[string][]EntityName{\n")
	for _, setName := range sortedEntitySetNames(catalog) {
		fmt.Fprintf(out, "\t%s: {%s},\n", strconv.Quote(setName), goEntityNames(catalog.EntitySets[setName]))
	}
	out.WriteString("}\n\nfunc validateEntitySet(family, set string, entity EntityName) error {\n\tfor _, allowed := range EntitySets[set] {\n\t\tif entity == allowed { return nil }\n\t}\n\treturn fmt.Errorf(\"entity %q is not supported by route family %s\", entity, family)\n}\n\n")
}

func goFamilyParameters(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		if parameter == "entity" {
			parts[i] = "entity EntityName"
		} else {
			parts[i] = camelName(parameter) + " string"
		}
	}
	return strings.Join(parts, ", ")
}

func goFamilyParameterMap(parameters []string) string {
	parts := make([]string, len(parameters))
	for i, parameter := range parameters {
		value := camelName(parameter)
		if parameter == "entity" {
			value = "string(entity)"
		}
		parts[i] = strconv.Quote(parameter) + ": " + value
	}
	return strings.Join(parts, ", ")
}

